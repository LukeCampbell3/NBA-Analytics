# M. dense forward pass ------------------------------------------------------------
def _fake_batch(batch_size=4):
    return {
        "sport_id": torch.zeros(batch_size, dtype=torch.long),
        "entity_bucket": torch.randint(0, 100, (batch_size,)),
        "role_id": torch.zeros(batch_size, dtype=torch.long),
        "target_id": torch.zeros(batch_size, dtype=torch.long),
        "home_id": torch.zeros(batch_size, dtype=torch.long),
        "numeric": torch.randn(batch_size, 5),
        "missing": torch.zeros(batch_size, 5),
        "y_over": torch.randint(0, 2, (batch_size,)).float(),
        "y_over_mask": torch.ones(batch_size),
        "z_actual": torch.randn(batch_size),
        "z_valid": torch.ones(batch_size),
    }


def test_M_dense_forward_backward():
    model = UniversalModel(hidden_dim=16, n_heads=2, block_types=["dense", "dense"])
    out = model(_fake_batch())
    loss = out["prob_over_logit"].mean() + out["z_pred"].mean()
    loss.backward()
    assert out["prob_over"].shape == (4,)



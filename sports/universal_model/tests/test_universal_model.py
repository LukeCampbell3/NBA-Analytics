# Q. no expert overflow corruption ----------------------------------------------------
def test_Q_output_shape_stable_under_skewed_routing():
    """DISCLOSED: this build has no hard per-expert capacity limit (all
    experts computed, unselected masked -- see model/router.py docstring),
    so there is no token-dropping/overflow path to corrupt. This test
    instead verifies shape/value sanity holds even under an adversarially
    skewed batch (all-identical inputs, which pushes every token toward
    the same expert)."""
    layer = Top2MoEFFN(hidden_dim=16, n_experts=4)
    x = torch.ones(4, 8, 16)
    out, diag = layer(x)
    assert out.shape == (4, 8, 16)
    assert torch.isfinite(out).all()


# R. model save/load equality -----------------------------------------------------------
@pytest.mark.skipif(not (CHECKPOINTS_DIR / "dense_baseline.pt").exists(), reason="checkpoint not present (gitignored, regenerate via train/run_baselines.py)")
def test_R_checkpoint_roundtrip_equal_output():
    from sports.universal_model.train.checkpoints import load_checkpoint

    model, _ = load_checkpoint(CHECKPOINTS_DIR / "dense_baseline.pt")
    model.eval()
    batch = _fake_batch()
    with torch.no_grad():
        out1 = model(batch)["prob_over"]
    model2, _ = load_checkpoint(CHECKPOINTS_DIR / "dense_baseline.pt")
    model2.eval()
    with torch.no_grad():
        out2 = model2(batch)["prob_over"]
    assert torch.allclose(out1, out2)


# S. DRM mutation rollback --------------------------------------------------------------
def test_S_rollback_restores_exact_state():
    model = UniversalModel(hidden_dim=16, n_heads=2, block_types=["dense", "dense", "top2_moe"], n_experts=4)
    snap = snapshot(model)
    for layer in model.stem.moe_layers():
        layer.add_expert()
    restore(model, snap)
    restored = model.state_dict()
    for key, tensor in snap.items():
        assert restored[key].shape == tensor.shape
        assert torch.allclose(restored[key], tensor)


# T. DRM function-preserving birth --------------------------------------------------------
def test_T_expert_birth_is_function_preserving():
    model = UniversalModel(hidden_dim=16, n_heads=2, block_types=["dense", "dense", "top2_moe"], n_experts=4)
    model.eval()
    batch = _fake_batch()
    with torch.no_grad():
        before = model(batch)["prob_over"].clone()
    for layer in model.stem.moe_layers():
        layer.add_expert()
    with torch.no_grad():
        after = model(batch)["prob_over"]
    assert torch.allclose(before, after, atol=1e-5), "expert birth must not change model output at the instant of birth"


# U. provisional -> permanent transition ----------------------------------------------------
def test_U_budget_tracks_only_permanent_growth():
    budget = DRMBudget(max_mutation_attempts_per_cycle=3, max_total_param_growth=1000)
    budget.record(StructuralMutationRecord("m1", "expert_birth", "d", {}, {}, {}, 500, 0.1, "PERMANENT", "ok"))
    budget.record(StructuralMutationRecord("m2", "expert_birth", "d", {}, {}, {}, 500, 0.1, "REJECTED", "bad"))
    assert budget.total_param_growth == 500
    assert budget.can_afford(500)
    assert not budget.can_afford(501)


# V. rejected structure -> no output state change --------------------------------------------
def test_V_rejected_mutation_leaves_no_trace_after_rollback():
    model = UniversalModel(hidden_dim=16, n_heads=2, block_types=["dense", "top2_moe"], n_experts=4)
    n_experts_before = model.stem.moe_layers()[0].n_experts
    snap = snapshot(model)
    for layer in model.stem.moe_layers():
        layer.add_expert()
    restore(model, snap)  # simulates REJECTED decision
    assert model.stem.moe_layers()[0].n_experts == n_experts_before
    assert model.stem.moe_layers()[0].experts.w1.shape[0] == n_experts_before


